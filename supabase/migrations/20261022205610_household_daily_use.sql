CREATE FUNCTION public.reorder_household_photos(_ids uuid[]) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ DECLARE hid uuid;
BEGIN
 SELECT c.household_id INTO hid FROM public.my_context() c WHERE c.mode='account';
 PERFORM homehub_private.lock_household(hid,true);
 IF cardinality(_ids) IS NULL OR cardinality(_ids)<>(SELECT count(*) FROM public.household_photos WHERE household_id=hid)
 OR cardinality(_ids)<>(SELECT count(DISTINCT i) FROM unnest(_ids) i)
 OR EXISTS(SELECT 1 FROM unnest(_ids) i WHERE NOT EXISTS(SELECT 1 FROM public.household_photos WHERE id=i AND household_id=hid)) THEN RAISE EXCEPTION 'Photo order changed; refresh and retry' USING ERRCODE='40001'; END IF;
 UPDATE public.household_photos p SET position=i.n-1 FROM unnest(_ids) WITH ORDINALITY AS i(id,n) WHERE p.id=i.id AND p.household_id=hid;
END $$;
