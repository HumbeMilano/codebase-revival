CREATE OR REPLACE FUNCTION public.redeem_invite(_code text,_pin text)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE inv public.invites; mkey text:='m_'||encode(extensions.gen_random_bytes(8),'hex');
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Not signed in'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(auth.uid()::text,0));
 IF _pin IS NULL OR _pin !~ '^[0-9]{4}$' THEN RAISE EXCEPTION 'PIN must be 4 digits'; END IF;
 SELECT * INTO inv FROM public.invites WHERE code=upper(trim(_code)) AND used_at IS NULL AND revoked_at IS NULL AND expires_at>now() FOR UPDATE;
 IF inv.code IS NULL THEN RAISE EXCEPTION 'Invalid or expired invite'; END IF;
 IF inv.recipient_email IS NOT NULL AND NOT EXISTS(SELECT 1 FROM auth.users u WHERE u.id=auth.uid() AND u.email_confirmed_at IS NOT NULL AND lower(u.email)=inv.recipient_email) THEN RAISE EXCEPTION 'This invitation belongs to a different verified email' USING ERRCODE='42501'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('homehub:'||inv.household_id::text,0));
 IF EXISTS(SELECT 1 FROM public.households WHERE id=inv.household_id AND suspended) THEN RAISE EXCEPTION 'Household suspended'; END IF;
 IF EXISTS(SELECT 1 FROM public.household_accounts WHERE user_id=auth.uid()) THEN RAISE EXCEPTION 'Already in household'; END IF;
 BEGIN INSERT INTO public.members(household_id,key,name,role,pin_hash) VALUES(inv.household_id,mkey,inv.member_name,inv.role,encode(extensions.digest(_pin,'sha256'),'hex'));
 EXCEPTION WHEN unique_violation THEN RAISE EXCEPTION 'PIN already in use'; END;
 INSERT INTO public.household_accounts(user_id,household_id,member_key) VALUES(auth.uid(),inv.household_id,mkey);
 UPDATE public.invites SET used_at=now() WHERE code=inv.code; RETURN inv.household_id;
END $$;

-- Durable shopping retries use caller-bound idempotency receipts. Financial and
-- other collections are deliberately excluded from the offline queue.
CREATE TABLE homehub_private.shopping_receipts(
 household_id uuid NOT NULL REFERENCES public.households ON DELETE CASCADE,
 actor text NOT NULL, mutation_id uuid NOT NULL, request_hash text NOT NULL,
 result jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(household_id,actor,mutation_id)
);
ALTER TABLE homehub_private.shopping_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON homehub_private.shopping_receipts FROM PUBLIC,anon,authenticated;
CREATE FUNCTION public.sync_shopping(_household uuid,_mutation_id uuid,_changes jsonb,_member_key text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE actor_id text; digest text; receipt homehub_private.shopping_receipts; saved jsonb;
BEGIN
 PERFORM homehub_private.lock_household(_household);
 IF _mutation_id IS NULL OR jsonb_typeof(_changes) IS DISTINCT FROM 'array' OR jsonb_array_length(_changes)>100 THEN RAISE EXCEPTION 'Invalid shopping mutation' USING ERRCODE='22023'; END IF;
 IF auth.uid() IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.my_context() c WHERE c.household_id=_household AND c.member_key=_member_key) THEN RAISE EXCEPTION 'Household member changed; sign in again' USING ERRCODE='42501'; END IF;
 actor_id:=CASE WHEN auth.uid() IS NOT NULL THEN 'account:'||auth.uid()::text ELSE 'device:'||encode(extensions.digest(coalesce(nullif(current_setting('request.headers',true),'')::jsonb->>'x-device-token',''),'sha256'),'hex') END;
 digest:=encode(extensions.digest(_changes::text,'sha256'),'hex');
 SELECT * INTO receipt FROM homehub_private.shopping_receipts WHERE household_id=_household AND actor=actor_id AND mutation_id=_mutation_id;
 IF receipt.mutation_id IS NOT NULL THEN
  IF receipt.request_hash<>digest THEN RAISE EXCEPTION 'Mutation identity reused with different data' USING ERRCODE='22023'; END IF;
  RETURN receipt.result;
 END IF;
 saved:=public.save_collection('shopping_items',_household,_changes);
 INSERT INTO homehub_private.shopping_receipts(household_id,actor,mutation_id,request_hash,result) VALUES(_household,actor_id,_mutation_id,digest,saved);
 DELETE FROM homehub_private.shopping_receipts WHERE household_id=_household AND created_at<now()-interval '30 days';
 RETURN saved;
END $$;
REVOKE ALL ON FUNCTION public.sync_shopping(uuid,uuid,jsonb,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.sync_shopping(uuid,uuid,jsonb,text) TO anon,authenticated;

