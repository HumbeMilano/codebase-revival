CREATE FUNCTION public.prepare_email_invite(_member_name text,_role text,_email text,_code text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE hid uuid; inv public.invites; recipient text:=lower(trim(_email));
BEGIN
 SELECT c.household_id INTO hid FROM public.my_context() c WHERE c.mode='account';
 PERFORM homehub_private.lock_household(hid,true);
 IF length(trim(coalesce(_member_name,''))) NOT BETWEEN 1 AND 100 OR _role NOT IN('admin','member') OR _role IS NULL
 OR length(coalesce(recipient,'')) NOT BETWEEN 3 AND 254 OR recipient !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$' THEN RAISE EXCEPTION 'Valid name, role and email required' USING ERRCODE='22023'; END IF;
 IF(SELECT count(*) FROM homehub_private.invite_email_attempts WHERE household_id=hid AND attempted_at>now()-interval '1 hour')>=20 THEN RAISE EXCEPTION 'Invitation email limit reached; try later' USING ERRCODE='54000'; END IF;
 IF _code IS NOT NULL THEN
  SELECT * INTO inv FROM public.invites WHERE code=_code AND household_id=hid AND recipient_email=recipient AND used_at IS NULL AND revoked_at IS NULL AND expires_at>now() FOR UPDATE;
  IF inv.code IS NULL THEN RAISE EXCEPTION 'Invalid or expired invite'; END IF;
 ELSE
  SELECT * INTO inv FROM public.invites WHERE household_id=hid AND recipient_email=recipient AND member_name=trim(_member_name) AND role=_role AND delivery_status='pending' AND used_at IS NULL AND revoked_at IS NULL AND expires_at>now() ORDER BY expires_at DESC LIMIT 1 FOR UPDATE;
  IF inv.code IS NULL THEN
   INSERT INTO public.invites(code,household_id,member_name,role,created_by,expires_at,recipient_email,delivery_status)
   VALUES(upper(encode(extensions.gen_random_bytes(16),'hex')),hid,trim(_member_name),_role,auth.uid(),now()+interval '7 days',recipient,'pending') RETURNING * INTO inv;
  END IF;
 END IF;
 IF inv.last_email_attempt_at>now()-interval '1 minute' THEN RAISE EXCEPTION 'Wait a minute before resending this invitation' USING ERRCODE='54000'; END IF;
 -- A deliberate resend gets a new delivery identity. An uncertain pending
 -- delivery keeps its identity so a retry cannot send the same message twice.
 UPDATE public.invites SET last_email_attempt_at=now(),delivery_status='pending',
 email_delivery_id=CASE WHEN delivery_status='sent' THEN gen_random_uuid() ELSE email_delivery_id END
 WHERE code=inv.code RETURNING * INTO inv;
 INSERT INTO homehub_private.invite_email_attempts(household_id) VALUES(hid);
 DELETE FROM homehub_private.invite_email_attempts WHERE household_id=hid AND attempted_at<now()-interval '1 day';
 RETURN jsonb_build_object('code',inv.code,'delivery_id',inv.email_delivery_id,'email',inv.recipient_email,'name',inv.member_name,'household_name',(SELECT name FROM public.households WHERE id=hid),'status',inv.delivery_status);
END $$;
